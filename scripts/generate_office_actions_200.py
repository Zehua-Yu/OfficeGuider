def main() -> None:
    random.seed(42)
    names: list[str] = []
    used: set[str] = set()
    vi, ti = 0, 0
    while len(names) < 200:
        v = VERBS[vi % len(VERBS)]
        t = TARGETS[ti % len(TARGETS)]
        ti += 1
        if ti % 3 == 0:
            vi += 1
        s = f"{v}「{t}」"
        if s in used:
            s = f"{v}「{t}」#{len(used)}"
        used.add(s)
        names.append(s)

    atoms: dict = {}
    rng = random.Random(42)
    for i in range(200):
        aid = f"sf_act_{i + 1:04d}"
        angle = 2 * math.pi * i / 200
        r = 0.15 + 0.75 * math.sqrt((i + 1) / 200)
        jx = rng.uniform(-0.04, 0.04)
        jy = rng.uniform(-0.04, 0.04)
        x = max(-1.0, min(1.0, r * math.cos(angle) + jx))
        y = max(-1.0, min(1.0, r * math.sin(angle) + jy))
        atoms[aid] = {
            "display_name": names[i],
            "x": round(x, 6),
            "y": round(y, 6),
            "complexity": round(0.15 + 0.85 * rng.random(), 3),
            "est_duration_sec": round(30 + 420 * rng.random()),
        }

    OUT.parent.mkdir(parents=True, exist_ok=True)
    payload = {"version": 1, "description": "200 office actions with 2D coords for VON", "atoms": atoms}
    OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Wrote {len(atoms)} atoms to {OUT}")


if __name__ == "__main__":
    main()
